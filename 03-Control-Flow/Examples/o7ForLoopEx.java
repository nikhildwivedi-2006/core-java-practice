public class o7ForLoopEx {

    public static void main(String[] args) {

        // Example 1: Print 1 to 5
        for (int i = 1; i <= 5; i++) {
            System.out.println(i);
        }

        System.out.println();

        // Example 2: Print 5 to 1
        for (int i = 5; i >= 1; i--) {
            System.out.println(i);
        }

        System.out.println();

        // Example 3: Print Even Numbers
        for (int i = 2; i <= 10; i += 2) {
            System.out.println(i);
        }

    }

}
public class o5WhileLoopEx {

    public static void main(String[] args) {

        // Example 1: Print 1 to 5
        int i = 1;

        while (i <= 5) {
            System.out.println(i);
            i++;
        }

        System.out.println();

        // Example 2: Print 5 to 1
        int number = 5;

        while (number >= 1) {
            System.out.println(number);
            number--;
        }

    }

}